/**
 * @file morse-encoder.h
 * @brief 超軽量・ポータブル モールス符号エンコーダーモジュールの公開ヘッダー
 * @details 入力文字列を国際モールス規格に準拠した符号データ（短点:1, 長点:3, 文字間空け:3, 単語間空け:7ユニット）
 *          へ順次変換（エンコード）するストリーム処理機能を提供します。
 *          単一インスタンスでの運用に最適化された省メモリ設計で、特定のハードウェア（LED/ブザーなど）に
 *          依存しない抽象化された符号化処理を行います。
 *
 * @copyright Copyright (c) 2026 Embedead-Inside
 * @license SPDX-License-Identifier: MIT-0
 */


#ifndef MORSE_ENCODER_H
#define MORSE_ENCODER_H

#include <stdint.h>

/* ========================================================================
 * 定数定義
 * ======================================================================== */

/**
 * @brief モールス信号の 1 ユニットあたりの基本時間（ミリ秒）
 * @details 国際モールス符号の基準速度（短点 1 点分＝1 ユニット）を設定します。
 */
#define MORSE_UNIT_TIME_MS  (100U)

/* ========================================================================
 * ハードウェア依存関数プロトタイプ（各 BSP / HAL 側で定義）
 * ======================================================================== */

/**
 * @brief 物理的な信号（LED、ブザー、GPIO等）の ON/OFF を制御する抽象化関数
 * @details リンクされる BSP 側の C ファイル内で物理レジスタ操作等を実装してください。
 * @param[in] active 信号の状態 (1: マーク/ON/発光/発音, 0: スペース/OFF/消灯/消音)
 * @return なし
 */
void morse_set_signal(uint8_t active);

/**
 * @brief システムの経過時間（ミリ秒）を取得する抽象化関数
 * @details リンクされる BSP 側の C ファイル内でタイマー割り込みや SysTick 等のカウント値を返してください。
 * @return uint32_t システム起動からの経過ミリ秒数
 */
uint32_t morse_get_time_ms(void);

/* ========================================================================
 * コア API プロトタイプ
 * ======================================================================== */

/**
 * @brief モールス送信モジュールの初期化関数
 * @details 内部状態変数およびスペース管理フラグをすべてリセットし、物理出力を OFF に設定します。
 *          システムの起動時や送信状態のリセット時に呼び出してください。
 * @return なし
 */
void morse_init(void);

/**
 * @brief モールス信号送信開始関数
 * @details 送信したい ASCII 文字列（ヌル終端）をセットし、送信シーケンスを開始します。
 *          本関数自体は即座に復帰し、実際の出力は morse_update() の呼び出しによって行われます。
 * @param[in] ascii_str 送信対象の ASCII 文字列（ヌル終端）
 * @return なし
 */
void morse_start(const char *ascii_str);

/**
 * @brief モールス送信状態更新関数（ノンブロッキング処理）
 * @details メインループまたは定期タスクから継続的に呼び出してください。
 *          内部タイマーと照合し、時間が到達している場合のみ物理出力と状態遷移を行います。
 * @return なし
 */
void morse_update(void);

/**
 * @brief 送信状態（ビジー状態）確認関数
 * @details モジュールが現在モールス信号を送信中（または文字間・単語間のウェイト中）か判定します。
 * @return uint8_t 送信状態 (1: 送信処理実行中, 0: 完全停止/待機中)
 */
uint8_t morse_is_busy(void);

#endif /* MORSE_ENCODER_H */
